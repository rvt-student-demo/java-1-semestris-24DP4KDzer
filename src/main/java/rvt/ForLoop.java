package rvt;
public class ForLoop {
    public static void main(String[] args){
        //stem
        
        int number = 1;
        while(number <= 6){
            System.out.println(number);
            number += 1;
        }

        System.out.println();


        for (int i = 0; i < 10; i++){
            System.out.println(i + 1);
        
        }
    }
}
